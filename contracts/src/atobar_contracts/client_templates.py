def render_into(
    m: TenantManifest, cp_url: str, client_dir: pathlib.Path, tenants_dir: pathlib.Path = TENANTS_DIR
) -> list[str]:
    """Writes generated files into a Client Repo checkout and returns their repo-relative paths."""
    cp_url = cp_url.rstrip("/")
    written: dict[str, str] = {
        ".github/workflows/flow-trigger.yml": render_trigger(m.slug, cp_url),
        ".github/workflows/flow-metrics.yml": render_metrics(m, cp_url),
        ".github/ISSUE_TEMPLATE/flow-task.md": render_issue_template(m.slug),
        ".github/PULL_REQUEST_TEMPLATE.md": render_pr_template(m.slug),
        ".github/REVIEW_TEMPLATE.md": render_review_template(m.slug),
    }
    for rel, text in written.items():
        dest = client_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(text)
    paths = sorted(written)
    extra = tenants_dir / m.slug / "client"
    if extra.is_dir():
        for src in sorted(p for p in extra.rglob("*") if p.is_file()):
            rel = src.relative_to(extra).as_posix()
            dest = client_dir / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dest)
            paths.append(rel)
    return paths
