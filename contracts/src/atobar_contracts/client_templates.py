def resolve_cp_hostname(explicit: str | None = None) -> str:
    """Resolves the Control Panel hostname from explicit arg, CP_HOSTNAME, or CP_PUBLIC_URL/CONTROL_PANEL_URL."""
    for candidate in (explicit, os.environ.get("CP_HOSTNAME")):
        if candidate and candidate.strip():
            clean = candidate.strip()
            if "://" in clean:
                clean = clean.split("://", 1)[1]
            return clean.split("/", 1)[0].strip()
    for url_candidate in (
        os.environ.get("CP_PUBLIC_URL"),
        os.environ.get("CONTROL_PANEL_URL"),
        os.environ.get("ATOBAR_CP_URL"),
    ):
        if url_candidate and url_candidate.strip():
            clean = url_candidate.strip()
            if "://" in clean:
                clean = clean.split("://", 1)[1]
            return clean.split("/", 1)[0].strip()
    return DEFAULT_CP_HOSTNAME


def resolve_cp_url(explicit: str | None = None) -> str:
    """Resolves the Control Panel URL from explicit arg, CP_PUBLIC_URL, CONTROL_PANEL_URL, or https://$CP_HOSTNAME."""
    for candidate in (
        explicit,
        os.environ.get("CP_PUBLIC_URL"),
        os.environ.get("CONTROL_PANEL_URL"),
        os.environ.get("ATOBAR_CP_URL"),
    ):
        if candidate and candidate.strip():
            clean = candidate.strip().rstrip("/")
            if not clean.startswith(("http://", "https://")):
                clean = f"https://{clean}"
            return clean
    host = os.environ.get("CP_HOSTNAME", "").strip().rstrip("/")
    if host:
        return host if host.startswith(("http://", "https://")) else f"https://{host}"
    return DEFAULT_CP_URL


def onboard_script_url(cp_url: str | None = None) -> str:
    return f"{resolve_cp_url(cp_url)}/onboard.sh"


def onboard_command(cp_url: str | None = None) -> str:
    return f"curl -fsSL {onboard_script_url(cp_url)} | bash"


def render_onboard_script(cp_url: str | None = None, app_slug: str = "atobar-flow-agent") -> str:
    """Renders scripts/onboard.sh with the Control Panel's public URL and GitHub App slug."""
    clean_url = resolve_cp_url(cp_url)
    clean_slug = (app_slug or "atobar-flow-agent").strip()
    candidates = [
        pathlib.Path(__file__).resolve().parents[3] / "scripts" / "onboard.sh",
        pathlib.Path("/app/scripts/onboard.sh"),
        pathlib.Path("scripts/onboard.sh"),
    ]
    raw_text = ""
    for candidate in candidates:
        if candidate.is_file():
            raw_text = candidate.read_text(encoding="utf-8")
            break
    if not raw_text:
        raise FileNotFoundError("scripts/onboard.sh not found")
    rendered = raw_text.replace(DEFAULT_CP_URL, clean_url)
    rendered = rendered.replace(
        'APP_SLUG="${ATOBAR_APP_SLUG:-atobar-flow-agent}"',
        f'APP_SLUG="${{ATOBAR_APP_SLUG:-{clean_slug}}}"',
    )
    return rendered

