def pick_metric_compiler_session(rows: list[dict[str, Any]], tenant_id: str, key: str) -> Optional[dict[str, Any]]:
    """The newest `metric_compiler` session for one metric (its `current_todo` is `compile:<key>[ ...]`)."""
    prefix = f"compile:{key}"

    def _is_for_key(r: dict[str, Any]) -> bool:
        todo = str(r.get("current_todo") or "")
        return todo == prefix or todo.startswith(prefix + " ") or str(r.get("run_id") or "").endswith(f"__{key}")

    matches = [
        r
        for r in rows
        if r.get("tenant_id") == tenant_id
        and str(r.get("status") or "").lower() != "dispatched"  # pending-<run_id> placeholder superseded by a real row
        and _is_for_key(r)
    ]
    return max(matches, key=lambda r: str(r.get("heartbeat_at") or ""), default=None)
