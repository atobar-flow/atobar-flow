@dataclass(frozen=True)
class Tenant:
    id: str
    repo: str
    status: str
    arbitration_mode: str
    manifest: dict[str, Any]
    repository_id: Optional[str] = None


def default_manifest(repo: str, created_by: str) -> dict[str, Any]:
    default_owner = (
        created_by.strip()
        if (created_by and created_by.strip() and created_by.strip() != "admin")
        else (repo.split("/", 1)[0] if "/" in repo else "")
    )
    return {
        "repo": repo,
        "owner_github_login": default_owner,
        "arbitration": {"mode": "shadow"},
        "metrics": [],
        "created_by": created_by,
    }


