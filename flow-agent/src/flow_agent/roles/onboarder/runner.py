"""Execution entrypoint for the ONBOARDER role (#301 WP-6).

Synthesizes the tenant SotaWiki with the model the Control Panel configured, publishes it through the run
credential, and opens one PR with the factory-generated client workflows. Every step fails the run loudly.
"""

import asyncio
import os
import pathlib
import subprocess
from typing import Any, Optional

from atobar_contracts.client_templates import render_into
from atobar_contracts.github_rest import RealGitHubClient
from atobar_contracts.manifest import TenantManifest
from flow_agent.knowledge.onboard_repo import synthesize_wiki, upsert_wiki_to_control_plane
from flow_agent.llm.factory import get_client
from flow_agent.llm.protocol import LLMClient
from flow_agent.roles.base import TurnOutcome
from flow_agent.runtime.key_delivery import fetch_run_llm_key, require_model

ONBOARDING_BRANCH = "atobar/onboarding"
ONBOARDING_TITLE = "chore(atobar): onboard to atobar-flow"


class OnboardingError(RuntimeError):
    """Onboarding could not complete; the run halts with this reason."""


def _git(workspace: str, *args: str) -> str:
    res = subprocess.run(["git", *args], cwd=workspace, capture_output=True, text=True, check=False)
    if res.returncode != 0:
        raise OnboardingError(f"git {args[0]} failed: {(res.stderr or res.stdout).strip()[:300]}")
    return res.stdout.strip()


def publish_onboarding_pr(
    workspace: str, paths: list[str], tenant: str, base: str, gh_client: Optional[RealGitHubClient]
) -> Optional[dict[str, Any]]:
    """Commits the rendered client files on `atobar/onboarding` and opens (or reuses) the PR; None if nothing changed."""
    if not paths:
        return None
    _git(workspace, "checkout", "-B", ONBOARDING_BRANCH)
    _git(workspace, "add", "--", *paths)
    if not _git(workspace, "diff", "--cached", "--name-only"):
        return None
    if gh_client is None:
        raise OnboardingError("no GitHub token on this run; cannot open the onboarding PR")
    _git(workspace, "commit", "-m", ONBOARDING_TITLE)
    _git(workspace, "push", "--force", "origin", f"HEAD:refs/heads/{ONBOARDING_BRANCH}")
    return gh_client.create_pull(
        tenant, ONBOARDING_BRANCH, base, ONBOARDING_TITLE, "Generated by atobar-flow onboarding."
    )


async def run_onboarder(
    tenant: str,
    workspace: str,
    manifest: Optional[dict[str, Any]],
    gh_client: Optional[RealGitHubClient] = None,
    llm: Optional[LLMClient] = None,
) -> TurnOutcome:
    cp_url = (os.environ.get("CONTROL_PANEL_URL") or os.environ.get("CP_URL") or "").rstrip("/")
    run_id = os.environ.get("FLOW_RUN_ID", "")
    cred = os.environ.get("FLOW_RUN_CREDENTIAL", "")
    if not (cp_url and run_id and cred):
        raise OnboardingError("missing CONTROL_PANEL_URL / FLOW_RUN_ID / FLOW_RUN_CREDENTIAL")
    if not pathlib.Path(workspace).is_dir():
        raise OnboardingError(f"workspace {workspace} does not exist")

    raw = dict(manifest or {})
    raw.pop("created_by", None)
    raw.setdefault("repo", tenant)
    raw.setdefault("owner_github_login", tenant.split("/", 1)[0])
    if raw.get("metrics"):
        m_obj = TenantManifest.model_validate(raw)
    else:
        # A tenant being onboarded has no approved metrics yet: validate everything else, render no metric steps.
        placeholder = {"key": "onboarding", "run": "echo 0", "comparator": "==", "threshold": 0}
        m_obj = TenantManifest.model_validate({**raw, "metrics": [placeholder]}).model_copy(update={"metrics": []})

    if llm is None:
        key_info = await asyncio.to_thread(fetch_run_llm_key, cp_url, run_id, cred)
        llm = get_client(key_info.provider, require_model(key_info), key_info.api_key)
    head = await asyncio.to_thread(_git, workspace, "rev-parse", "HEAD")
    wiki = await asyncio.to_thread(synthesize_wiki, workspace, tenant, llm)
    if head:
        wiki = wiki.model_copy(update={"commit_sha": head})
    if not await asyncio.to_thread(upsert_wiki_to_control_plane, tenant, wiki):
        raise OnboardingError("publishing the SotaWiki to the Control Panel failed")

    raw_issue_id = (os.environ.get("ISSUE_ID") or "0").strip()
    issue_id = int(raw_issue_id) if raw_issue_id.isdigit() else 0
    if issue_id > 0:
        paths = render_into(m_obj, cp_url, pathlib.Path(workspace))
        await asyncio.to_thread(publish_onboarding_pr, workspace, paths, tenant, m_obj.default_branch, gh_client)
        head = await asyncio.to_thread(_git, workspace, "rev-parse", "HEAD")
    return TurnOutcome(envelope_text="", head_sha=head)
